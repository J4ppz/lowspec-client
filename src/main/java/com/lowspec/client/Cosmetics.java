package com.lowspec.client;

import java.lang.reflect.Constructor;
import java.lang.reflect.RecordComponent;
import java.net.URI;
import java.net.URLEncoder;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.charset.StandardCharsets;
import java.time.Duration;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import java.util.UUID;
import java.util.concurrent.ConcurrentHashMap;

import com.google.gson.JsonObject;
import com.google.gson.JsonParser;

import net.fabricmc.api.ClientModInitializer;
import net.fabricmc.fabric.api.client.event.lifecycle.v1.ClientTickEvents;
import net.minecraft.client.Minecraft;
import net.minecraft.client.player.AbstractClientPlayer;
import net.minecraft.resources.Identifier;
import net.minecraft.world.entity.player.PlayerSkin;

/**
 * Capes. Your own choice applies instantly; other LowSpec players' choices are fetched by name from
 * the same Cloudflare Worker that Friends uses. The skin swap is done through reflection so a renamed
 * field can only mean "no cape", never a broken build.
 */
public class Cosmetics implements ClientModInitializer {

    /** Index = value of the Cape option. 0 means none. Files are generated by tools/gen_capes.py. */
    static final String[] NAMES = {"", "aurora", "ember", "ocean", "void", "mint", "sunset"};

    private static final HttpClient HTTP = HttpClient.newBuilder()
            .connectTimeout(Duration.ofSeconds(5)).build();

    private static final ConcurrentHashMap<String, Integer> remote = new ConcurrentHashMap<>();
    private static final ConcurrentHashMap<String, Long> asked = new ConcurrentHashMap<>();
    private static final Set<String> wanted = ConcurrentHashMap.newKeySet();

    private record Cached(PlayerSkin original, int cape, PlayerSkin result) { }

    private static final ConcurrentHashMap<UUID, Cached> CACHE = new ConcurrentHashMap<>();

    private static int published = -1;
    private static String publishedName = "";
    private static int ticks;

    @Override
    public void onInitializeClient() {
        ClientTickEvents.END_CLIENT_TICK.register(Cosmetics::tick);
    }

    // ---------- used by the mixin ----------

    /** Returns a copy of the skin with our cape, or null to leave the skin alone. */
    public static PlayerSkin apply(AbstractClientPlayer player, PlayerSkin skin) {
        if (skin == null) return null;
        int cape = capeIdFor(player);
        if (cape <= 0 || cape >= NAMES.length) return null;

        UUID id = player.getUUID();
        Cached c = CACHE.get(id);
        if (c != null && c.cape() == cape && c.original().equals(skin)) return c.result();

        PlayerSkin rebuilt = rebuild(skin, cape);
        if (rebuilt != null) CACHE.put(id, new Cached(skin, cape, rebuilt));
        return rebuilt;
    }

    private static int capeIdFor(AbstractClientPlayer p) {
        if (!LowSpecClient.Settings.has(LowSpecClient.Mod.COSMETICS)) return 0;
        Minecraft mc = Minecraft.getInstance();
        if (p == mc.player) return LowSpecClient.Settings.get(LowSpecClient.O.CAPE);

        String n = p.getName().getString().toLowerCase(Locale.ROOT);
        if (!n.matches("[a-z0-9_]{1,16}")) return 0;
        Integer c = remote.get(n);
        if (Friends.enabled()) {
            Long t = asked.get(n);
            if (t == null || System.currentTimeMillis() - t > 300_000L) wanted.add(n);
        }
        return c == null ? 0 : c;
    }

    // ---------- rebuilding the skin ----------
    private static PlayerSkin rebuild(PlayerSkin skin, int cape) {
        try {
            RecordComponent[] rc = PlayerSkin.class.getRecordComponents();
            Class<?>[] types = new Class<?>[rc.length];
            Object[] args = new Object[rc.length];
            boolean replaced = false;
            for (int i = 0; i < rc.length; i++) {
                types[i] = rc[i].getType();
                Object v = rc[i].getAccessor().invoke(skin);
                if (rc[i].getName().toLowerCase(Locale.ROOT).contains("cape")) {
                    Object tex = makeTexture(types[i], cape);
                    if (tex == null) return null;
                    v = tex;
                    replaced = true;
                }
                args[i] = v;
            }
            if (!replaced) return null;
            return PlayerSkin.class.getDeclaredConstructor(types).newInstance(args);
        } catch (ReflectiveOperationException | RuntimeException e) {
            return null;
        }
    }

    private static Object makeTexture(Class<?> type, int cape) throws ReflectiveOperationException {
        String path = "cape/" + NAMES[cape];
        Identifier id = Identifier.fromNamespaceAndPath("lowspec", path);
        Identifier file = Identifier.fromNamespaceAndPath("lowspec", "textures/" + path + ".png");
        if (type == Identifier.class) return file;

        Class<?> rt = Class.forName("net.minecraft.core.ClientAsset$ResourceTexture");
        if (!type.isAssignableFrom(rt)) return null;
        Constructor<?> one = null;
        for (Constructor<?> k : rt.getConstructors()) {
            Class<?>[] p = k.getParameterTypes();
            if (p.length == 2 && p[0] == Identifier.class && p[1] == Identifier.class) return k.newInstance(id, file);
            if (p.length == 1 && p[0] == Identifier.class) one = k;
        }
        return one == null ? null : one.newInstance(id);
    }

    // ---------- talking to the backend ----------
    private static HttpRequest.Builder req(String path) {
        return HttpRequest.newBuilder(URI.create(Friends.backend + path))
                .timeout(Duration.ofSeconds(8))
                .header("x-key", Friends.key)
                .header("content-type", "application/json");
    }

    private static void tick(Minecraft mc) {
        if (++ticks % 40 != 0 || mc.player == null || !Friends.enabled()) return; // every ~2 s

        String name = mc.getUser().getName();
        int cape = LowSpecClient.Settings.get(LowSpecClient.O.CAPE);
        if (cape != published || !name.equals(publishedName)) {
            JsonObject o = new JsonObject();
            o.addProperty("code", Friends.myCode);
            o.addProperty("name", name);
            o.addProperty("cape", cape);
            try {
                HTTP.sendAsync(req("/setcape").POST(HttpRequest.BodyPublishers.ofString(o.toString())).build(),
                        HttpResponse.BodyHandlers.discarding());
            } catch (RuntimeException ignored) {
            }
            published = cape;
            publishedName = name;
        }

        if (!wanted.isEmpty()) fetch();
    }

    private static void fetch() {
        List<String> batch = new ArrayList<>();
        for (String n : wanted) {
            batch.add(n);
            if (batch.size() >= 20) break;
        }
        wanted.removeAll(batch);
        long now = System.currentTimeMillis();
        for (String n : batch) asked.put(n, now);
        try {
            String names = URLEncoder.encode(String.join(",", batch), StandardCharsets.UTF_8);
            HTTP.sendAsync(req("/capes?names=" + names).GET().build(), HttpResponse.BodyHandlers.ofString())
                    .thenAccept(r -> {
                        if (r.statusCode() != 200) return;
                        try {
                            JsonObject capes = JsonParser.parseString(r.body()).getAsJsonObject()
                                    .getAsJsonObject("capes");
                            for (String n : batch) {
                                remote.put(n, capes.has(n) ? capes.get(n).getAsInt() : 0);
                            }
                        } catch (RuntimeException ignored) {
                        }
                    });
        } catch (RuntimeException ignored) {
        }
    }
}
